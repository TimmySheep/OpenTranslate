#!/usr/bin/env bash
# Refresh the Xcode project's bundled web resources from the latest WXT builds,
# WITHOUT re-running the converter (preserves signing / Info.plist / pbxproj hand edits).
# Auto-detects the extension target's Resources dir(s) regardless of converter layout.
#
# Also copies the App settings UI to:
#   apple/OpenTranslate/Shared (App)/Resources/settings/
# That folder is not yet in the Xcode project (pbxproj is owned by the iCloud
# task). Coordinator needs to add a folder reference — see the comment at the
# bottom of this file.
set -euo pipefail
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC_EXT="$REPO_ROOT/extension/.output/safari-mv3"
SRC_APP="$REPO_ROOT/extension/.output/options-app"
DEST_APP="$REPO_ROOT/apple/OpenTranslate/Shared (App)/Resources/settings"

missing=0
if [ ! -d "$SRC_EXT" ]; then
  echo "Missing $SRC_EXT"
  echo "Build first: scripts/build-safari.sh"
  missing=1
fi
if [ ! -d "$SRC_APP" ]; then
  echo "Missing $SRC_APP"
  echo "Build first: scripts/build-safari.sh  (also builds options-app)"
  missing=1
fi
[ "$missing" -eq 0 ] || exit 1

# Scope to the source project only (apple/OpenTranslate), NOT apple/DerivedData
# build products — those are regenerated by xcodebuild from the source.
CANONICAL_EXT="$REPO_ROOT/apple/OpenTranslate/Shared (Extension)/Resources"
RES_DIRS="$(/usr/bin/find "$REPO_ROOT/apple/OpenTranslate" -type d -path '*Extension*/Resources' 2>/dev/null || true)"
if [ -z "$RES_DIRS" ]; then
  # Fresh worktree: the extension Resources dir is gitignored and may not exist yet.
  mkdir -p "$CANONICAL_EXT"
  RES_DIRS="$CANONICAL_EXT"
  echo "Created $CANONICAL_EXT"
fi
printf '%s\n' "$RES_DIRS" | while IFS= read -r d; do
  [ -n "$d" ] || continue
  echo "→ syncing $SRC_EXT → $d"
  rsync -a --delete "$SRC_EXT"/ "$d"/
done

mkdir -p "$DEST_APP"
echo "→ syncing $SRC_APP → $DEST_APP"
rsync -a --delete "$SRC_APP"/ "$DEST_APP"/

echo "✓ Synced. Rebuild in Xcode (or via xcodebuild) to pick up the new bundle."
echo
echo "NOTE: pbxproj is not owned by this task. To actually pack settings/ into"
echo "the iOS and macOS app bundles, the coordinator must add a folder reference."
echo "Suggested IDs (unused as of 11EEF90A):"
echo "  11EEF90B2FE586BB003E1F8A  PBXFileReference  settings  lastKnownFileType=folder  path=settings"
echo "  11EEF90C2FE586BB003E1F8A  PBXBuildFile      settings in Resources (iOS App,  11EEF800…)"
echo "  11EEF90D2FE586BB003E1F8A  PBXBuildFile      settings in Resources (macOS App, 11EEF812…)"
echo "And add 11EEF90B… to group 11EEF7F4… /* Resources */ under Shared (App)."
